"""Offline framework integration with deterministic selector/transport doubles."""

import asyncio
import json
import time
from pathlib import Path
from typing import Any

from a2a.client import minimal_agent_card
from a2a.types import (
    AgentSkill,
    Artifact,
    Part,
    StreamResponse,
    Task,
    TaskState,
    TaskStatus,
)
from agent_framework import Agent, AgentResponse, Message
from agent_framework.a2a import A2AAgent
from agent_framework.orchestrations import GroupChatBuilder
from capability_preview import selection_description


class NoModelClient:
    async def get_response(self, *args: Any, **kwargs: Any) -> Any:
        raise AssertionError("No model call is allowed")


class RecordingSelector(Agent):
    """Keyword fixture consumes the actual framework selection prompt; not an LLM."""

    def __init__(self, keyword: str):
        super().__init__(client=NoModelClient(), name="selector")
        self.keyword = keyword
        self.prompts = []
        self.selected = None
        self.conversations = []

    async def run(self, messages=None, **kwargs):
        self.conversations.append([m.text for m in messages])
        prompt = messages[-1].text
        self.prompts.append(prompt)
        if len(self.prompts) == 1:
            section = prompt.split("and their descriptions:\n", 1)[1]
            # Candidate names are fixed and generated by this fixture.
            chunks = section.split("\nbeta: ")
            descriptions = {
                "alpha": chunks[0].removeprefix("alpha: "),
                "beta": chunks[1],
            }
            self.selected = next(
                (n for n, d in descriptions.items() if self.keyword in d.lower()), None
            )
        terminate = len(self.prompts) > 1 or self.selected is None
        payload = dict(
            terminate=terminate,
            reason="deterministic fixture",
            next_speaker=None if terminate else self.selected,
            final_message="fixture complete" if terminate else None,
        )
        return AgentResponse(
            messages=[Message("assistant", [json.dumps(payload)])], value=payload
        )


class RecordingTransport:
    def __init__(self, name):
        self.name = name
        self.requests = []

    async def send_message(self, request):
        self.requests.append(request)
        yield StreamResponse(
            task=Task(
                id=f"task-{self.name}",
                context_id="offline-fixture",
                status=TaskStatus(state=TaskState.TASK_STATE_COMPLETED),
                artifacts=[
                    Artifact(
                        artifact_id="answer",
                        parts=[Part(text=f"fixture executed {self.name}")],
                    )
                ],
            )
        )


CASES = [
    (
        "similar descriptions",
        "translate",
        [[("summarize", "Summarize text")], [("translate", "Translate text")]],
        ["beta"],
    ),
    (
        "multiple skills",
        "translate",
        [
            [("summarize", "Summarize text"), ("translate", "Translate text")],
            [("calculate", "Calculate")],
        ],
        ["alpha"],
    ),
    (
        "specialist",
        "spectroscopy",
        [[("spectroscopy", "Analyze spectroscopy")], [("calculate", "Calculate")]],
        ["alpha"],
    ),
    (
        "overlap",
        "translate",
        [[("translate", "Translate text")], [("translate", "Translate text")]],
        ["alpha", "beta"],
    ),
    (
        "no suitable agent",
        "surgery",
        [[("translate", "Translate text")], [("calculate", "Calculate")]],
        [],
    ),
    # Ground truth deliberately disagrees with the untrusted advertised claim.
    (
        "misleading skill",
        "surgery",
        [[("surgery", "Expert surgery")], [("calculate", "Calculate")]],
        [],
    ),
    (
        "incomplete description",
        "spectroscopy",
        [[("analysis", "")], [("calculate", "Calculate")]],
        ["alpha"],
    ),
]


async def main():
    rows = []
    for label, keyword, specs, acceptable in CASES:
        for treatment in (False, True):
            agents, transports, descriptions = [], [], []
            for name, skills in zip(("alpha", "beta"), specs):
                card = minimal_agent_card(f"https://{name}.invalid", ["JSONRPC"])
                card.name, card.description = name, "General purpose assistant"
                card.skills.extend(
                    [
                        AgentSkill(id=n, name=n, description=d, tags=[])
                        for n, d in skills
                    ]
                )
                description = (
                    selection_description(card) if treatment else card.description
                )
                descriptions.append(description)
                transport = RecordingTransport(name)
                transports.append(transport)
                agents.append(
                    A2AAgent(
                        agent_card=card,
                        description=description,
                        client=transport,
                        http_client=None,
                    )
                )
            selector = RecordingSelector(keyword)
            workflow = GroupChatBuilder(
                participants=agents, orchestrator_agent=selector
            ).build()
            started = time.perf_counter()
            result = await workflow.run(f"Please perform {keyword}")
            elapsed = (time.perf_counter() - started) * 1000
            selected = selector.selected
            correct = selected in acceptable if acceptable else selected is None
            requests = [r for t in transports for r in t.requests]
            assert len(requests) == (selected is not None)
            assert all(d in selector.prompts[0] for d in descriptions)
            assert all(not getattr(r, "metadata", None) for r in requests)
            assert all("skill_id" not in r.message.metadata for r in requests)
            if selected:
                assert any(
                    f"fixture executed {selected}" in text
                    for text in selector.conversations[-1]
                )
            rows.append(
                dict(
                    case=label,
                    arm="treatment" if treatment else "baseline",
                    selected=selected,
                    acceptable=acceptable,
                    correct=correct,
                    wrong_delegation=selected is not None
                    and selected not in acceptable,
                    no_match=selected is None,
                    transport_calls=len(requests),
                    latency_ms=elapsed,
                    description_chars=sum(map(len, descriptions)),
                    prompt=selector.prompts[0],
                    outputs=[str(o) for o in result.get_outputs()],
                    task_result_seen=selected is not None,
                    model_calls=0,
                    model_tokens=None,
                    model_cost=None,
                )
            )
    Path("results.json").write_text(json.dumps(rows, indent=2))
    for arm in ("baseline", "treatment"):
        subset = [r for r in rows if r["arm"] == arm]
        print(
            arm,
            json.dumps(
                dict(
                    samples=len(subset),
                    correct=sum(r["correct"] for r in subset),
                    wrong_delegations=sum(r["wrong_delegation"] for r in subset),
                    transport_calls=sum(r["transport_calls"] for r in subset),
                )
            ),
        )
    print("PASS: 14 real GroupChat/A2AAgent executions; model efficacy UNTESTED")


if __name__ == "__main__":
    asyncio.run(main())
